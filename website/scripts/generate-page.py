#!/usr/bin/env python3
"""Convert the authored marketing HTML into native React server markup."""
from pathlib import Path
from html.parser import HTMLParser
from html import unescape
import json,re
ROOT=Path(__file__).resolve().parents[1]
class Node:
 def __init__(self,tag='',attrs=None): self.tag=tag;self.attrs=dict(attrs or []);self.children=[]
class Parser(HTMLParser):
 def __init__(self):super().__init__(convert_charrefs=True);self.root=Node();self.stack=[self.root]
 def handle_starttag(self,tag,attrs):
  node=Node(tag,attrs);self.stack[-1].children.append(node)
  if tag not in {'img','br','input','meta','link','hr','source'}:self.stack.append(node)
 def handle_startendtag(self,tag,attrs):self.handle_starttag(tag,attrs);self.handle_endtag(tag) if self.stack[-1].tag==tag else None
 def handle_endtag(self,tag):
  for i in range(len(self.stack)-1,0,-1):
   if self.stack[i].tag==tag:self.stack=self.stack[:i];break
 def handle_data(self,data):self.stack[-1].children.append(data)
markup=(ROOT/'site/index.html').read_text();markup=markup[markup.index('<main '):markup.index('</main>')+7]
markup=markup.replace('{{HERO_SETUP_PANEL}}','<setup-panel></setup-panel>')
markup+='\n'+(ROOT/'partials/footer.html').read_text().replace('{{FOOTER_LAUNCH}}','<forest-footer></forest-footer>')
markup=markup.replace('{{DOCS_URL}}','__DOCS__')
parser=Parser();parser.feed(markup)
void={'img','br','input','hr','source'}
names={'class':'className','tabindex':'tabIndex','for':'htmlFor','fetchpriority':'fetchPriority','stroke-width':'strokeWidth','stroke-linecap':'strokeLinecap','stroke-linejoin':'strokeLinejoin','fill-rule':'fillRule','clip-rule':'clipRule','viewbox':'viewBox'}
def render(node):
 if isinstance(node,str):return '{'+json.dumps(node,ensure_ascii=False)+'}' if node.strip() or '\n' not in node else '\n'
 a=node.attrs;tag=node.tag
 if tag=='setup-panel':return '<SetupPanel />'
 if tag=='forest-footer':return '<ForestFooter />'
 if 'data-forest-scene' in a or 'data-agent-prompt-panel' in a and tag=='details':return ''
 if 'data-hero-trail' in a:return '<HeroTrail />'
 for kind in ['hero','cta','orbit']:
  if f'data-{kind}-landscape' in a:return '<Landscape kind="'+kind+'" className='+json.dumps(a.get('class',''))+' />'
 if 'data-feature-tile' in a:return '<div className="feature-tile" data-feature-tile='+json.dumps(a['data-feature-tile'])+'><FeatureTile feature='+json.dumps(a['data-feature-tile'])+' /></div>'
 if 'data-ascii-rest' in a:
  return '<RestArt piece='+json.dumps(a['data-ascii-rest'])+' logo={'+str('data-ascii-logo' in a).lower()+'} className='+json.dumps(a.get('class',''))+' aria-label='+json.dumps(a.get('aria-label',''))+' />'
 if a.get('class')=='setup-lab':return '<SetupLab />'
 if 'data-copy-command' in a:
  command=next(c for c in node.children if isinstance(c,Node) and c.tag=='code').children[0]
  return '<PlateCommand command='+json.dumps(command)+' />'
 if 'data-copy-agent-prompt' in a:return '<AgentPromptButton className='+json.dumps(a.get('class',''))+' />'
 if a.get('class') in ['agent-prompt-fallback','sr-only launch-status']:return ''
 if 'data-content-picker' in a:tag='ContentPicker'
 if 'data-lab-machine' in a:tag='LabLink';a['machine']=a.pop('data-lab-machine')
 attributes=[]
 for key,val in a.items():
  if key=='data-content-picker' or key.startswith('data-agent-'):continue
  key=names.get(key,key)
  if key=='checked':key='defaultChecked'
  if val is None:attributes.append(f'{key}={{true}}')
  elif val.startswith('__DOCS__'):attributes.append(f'{key}={{documentationOrigin + '+json.dumps(val[8:])+'}')
  elif key in ['tabIndex','width','height'] and val.lstrip('-').isdigit():attributes.append(key+'={'+val+'}')
  elif key=='style':
   style={re.sub(r'-([a-z])',lambda m:m[1].upper(),k.strip()):v.strip() for item in val.split(';') if ':' in item for k,v in [item.split(':',1)]};attributes.append('style={'+json.dumps(style)+'}')
  else:attributes.append(key+'='+json.dumps(val,ensure_ascii=False))
 start='<'+tag+(' '+' '.join(attributes) if attributes else '')
 return start+(' />' if tag in void else '>'+''.join(map(render,node.children))+'</'+tag+'>')
imports='''import { SetupPanel, AgentPromptButton, PlateCommand } from "@/components/setup-panel";
import { SetupLab } from "@/components/setup-lab";
import { ContentPicker, LabLink } from "@/components/content-picker";
import { RestArt, ForestFooter } from "@/components/rest-art";
import { Landscape, HeroTrail } from "@/components/landscape";
import { FeatureTile } from "@/components/feature-tile";
import { documentationOrigin } from "@/lib/documentation";
'''
(ROOT/'components/marketing-content.tsx').write_text('// Generated by scripts/generate-page.py from the authored marketing sections.\n'+imports+'\nexport function MarketingContent() { return <div className="marketing-content">'+''.join(map(render,parser.root.children))+'</div>; }\n')
