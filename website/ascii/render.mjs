import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { registerHooks } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { drawLabArt, labPaper } from "./lab-art.mjs";

const revision = "d5592fc980cad39578f13b16f6e015404160669b";
const sha256 = "0de00344a95abf51dc3f6242b0c8a695ef3222201269a4d4f31fb32bfee433a9";
const generated = `<!-- Generated by website/ascii/render.mjs using asciicn ${revision} (MIT). -->\n`;
const components = [ "terminal-window", "ascii-box", "loader", "progress-bar", "server-rack", "retro-computer", "glyph-trail", "redwood-light", "ember", "black-hole", "not-found"];
const dependencies = fileURLToPath(new URL("./node_modules", import.meta.url));
async function loadEngine(scratch) {
  const archive = join(scratch, "asciicn.tar.gz");
  const download = `https://codeload.github.com/opencoredev/asciicn/tar.gz/${revision}`;
  const localArchive = process.env.ASCIICN_ARCHIVE;
  const response = localArchive ? null : await fetch(download, { signal: AbortSignal.timeout(30_000) });
  if (response && !response.ok) throw new Error(`Could not download asciicn (HTTP ${response.status}).`);
  const bytes = localArchive ? await readFile(localArchive) : Buffer.from(await response.arrayBuffer());
  if (createHash("sha256").update(bytes).digest("hex") !== sha256) {
    throw new Error("The asciicn archive does not match its pinned SHA-256.");
  }
  await writeFile(archive, bytes);
  execFileSync("tar", ["-xzf", archive, "-C", scratch, "--strip-components=1",
    `asciicn-${revision}/lib/ascii`,
    ...components.map(name => `asciicn-${revision}/components/asciicn/${name}.tsx`),
    `asciicn-${revision}/LICENSE`,
  ]);

  const alias = "@/lib/ascii/";
  registerHooks({
    resolve(specifier, context, next) {
      if (specifier.startsWith(alias)) {
        specifier = pathToFileURL(join(scratch, "lib/ascii", `${specifier.slice(alias.length)}.ts`)).href;
      }
      return next(specifier, context);
    },
  });
  const { mapTones, MutableFrame } = await import("@/lib/ascii/frame");
  const { toSvg } = await import("@/lib/ascii/export");
  return { mapTones, MutableFrame, toSvg };
}

async function extractScene(scratch, name, startMarker, endMarker, exports) {
  const source = await readFile(join(scratch, `components/asciicn/${name}.tsx`), "utf8");
  const start = source.indexOf(startMarker);
  const end = source.indexOf(endMarker);
  if (start < 0 || end < start) throw new Error(`The pinned ${name} source has changed shape.`);
  const scene = join(scratch, `${name}-scene.ts`);
  await writeFile(scene, source.slice(start, end) + `\nexport { ${exports} };\n`);
  return scene;
}

async function addStaticTerminalContent(scratch) {
  const path = join(scratch, "components/asciicn/terminal-window.tsx");
  let source = await readFile(path, "utf8");
  // Keep the upstream frame and title while allowing native interactive content
  // in place of the scripted terminal screen.
  for (const [before, after] of [
    ['className="inline-flex items-baseline gap-[1ch]"', 'className="smu-terminal-title"'],
    ['className="tracking-[0.1em]"', 'className="smu-terminal-lights"'],
    ['  script?: readonly TerminalStep[];', '  script?: readonly TerminalStep[];\n  staticContent?: ReactNode;'],
    ['  script = DEFAULT_TERMINAL_SCRIPT,', '  staticContent,\n  script = staticContent === undefined ? DEFAULT_TERMINAL_SCRIPT : [],'],
    ['enabled: play === "playing"', 'enabled: staticContent === undefined && play === "playing"'],
    ['const footer: ReactNode = reduced ? null', 'const footer: ReactNode = reduced || staticContent !== undefined ? null'],
    ['    >\n      <style>{"@keyframes term-blink', '    >\n      {staticContent ?? <>\n      <style>{"@keyframes term-blink'],
    ['    </AsciiBox>\n  );', '      </>}\n    </AsciiBox>\n  );'],
  ]) {
    if (!source.includes(before)) throw new Error("The pinned Terminal Window has changed shape.");
    source = source.replace(before, after);
  }
  await writeFile(path, source);
}

async function addForestNotFoundColors(scratch) {
  const path = join(scratch, "components/asciicn/not-found.tsx");
  let source = await readFile(path, "utf8");
  const original = "[colors[at], colors[at + 1], colors[at + 2]] = ink;";
  if (!source.includes(original)) throw new Error("The pinned Not Found palette has changed shape.");
  // Retain upstream erosion and grain motion; light the digits like a forest canopy.
  source = source.replace(original, `
        const light = Math.min(1, Math.max(0,
          0.72 * (1 - y / height) + 0.28 * x / width
          + 0.07 * Math.sin(x / width * TAU - cycle)));
        const moss = [77, 116, 66];
        const fern = [153, 177, 100];
        const canopy = [239, 236, 172];
        const from = light < 0.5 ? moss : fern;
        const to = light < 0.5 ? fern : canopy;
        const blend = light < 0.5 ? light * 2 : (light - 0.5) * 2;
        for (let channel = 0; channel < 3; channel += 1) {
          colors[at + channel] = Math.round(from[channel] + (to[channel] - from[channel]) * blend);
        }
      `);
  await writeFile(path, source);
}

async function bundleAscii(scratch) {
  if (execFileSync("esbuild", ["--version"], { encoding: "utf8" }).trim() !== "0.25.9") {
    throw new Error("Artwork regeneration requires esbuild 0.25.9.");
  }
  const redwood = await extractScene(scratch, "redwood-light", "const SCENE =", "const SHADE =", "FIELD, COLOR_FIELD");
  const ember = await extractScene(scratch, "ember", "const SCENE =", "const clamp =", "FIELD, COLOR_FIELD");
  const blackHole = await extractScene(scratch, "black-hole", "const SCENE =", "const FALLBACK =", "FIELD, COLOR_FIELD");
  await addStaticTerminalContent(scratch);
  await addForestNotFoundColors(scratch);
  const license = await readFile(join(scratch, "LICENSE"), "utf8");
  const entries = {
    "hero-landscape": ["hero-landscape.mjs", `--alias:smu-redwood-scene=${redwood}`],
    "cta-landscape": ["cta-landscape.mjs", `--alias:smu-ember-scene=${ember}`],
    "orbit-landscape": ["orbit-landscape.mjs", `--alias:smu-black-hole-scene=${blackHole}`],
    "footer-landscape": ["footer-landscape.mjs"],
    "smooth-scroll": ["smooth-scroll.mjs", `--alias:lenis=${join(dependencies, "lenis/dist/lenis.mjs")}`],
    "not-found": ["not-found.jsx", "--jsx=automatic", '--define:process.env.NODE_ENV="production"',
      `--alias:@/components/asciicn=${join(scratch, "components/asciicn")}`,
      `--alias:@/lib/utils=${fileURLToPath(new URL("./terminal-classes.mjs", import.meta.url))}`],
    "lab-terminal": ["lab-terminal.jsx", "--jsx=automatic", '--define:process.env.NODE_ENV="production"',
      `--alias:@/components/asciicn=${join(scratch, "components/asciicn")}`,
      `--alias:@/lib/utils=${fileURLToPath(new URL("./terminal-classes.mjs", import.meta.url))}`],
  };
  return Object.fromEntries(Object.entries(entries).map(([name, [source, ...args]]) => [
    `${name}.js`,
    execFileSync("esbuild", [
      fileURLToPath(new URL(source, import.meta.url)),
      "--bundle", "--format=esm", "--target=es2022", "--minify",
      `--alias:@/lib/ascii=${join(scratch, "lib/ascii")}`,
      `--banner:js=/*! asciicn ${revision}\n${license}*/`,
      ...args,
    ], { encoding: "utf8", maxBuffer: 2_000_000, env: { ...process.env, NODE_PATH: dependencies } }),
  ]));
}

async function bundleTerminalStyles(scratch) {
  const input = join(scratch, "terminal.css");
  await writeFile(input, `
    @import "${dependencies}/tailwindcss/theme.css" layer(theme);
    @import "${dependencies}/tailwindcss/utilities.css" layer(utilities) source(none);
    @source "./components/asciicn";
    @theme { --color-foreground: #eff8ef; --color-muted-foreground: #c7dbc5; }
  `);
  return execFileSync(join(dependencies, ".bin/tailwindcss"), ["-i", input, "--minify"], { encoding: "utf8" });
}

async function renderStill({ toSvg }, name, height, paper, { width = 1440, shapes = false } = {}) {
  const snapshot = JSON.parse(await readFile(new URL(`./${name}-still.json`, import.meta.url), "utf8"));
  const { columns, rows, inks } = snapshot;
  const glyphs = Array.from(snapshot.glyphs);
  if (glyphs.length !== columns * rows || inks.length !== glyphs.length) {
    throw new Error("Invalid PETSCII still frame dimensions.");
  }
  const palette = snapshot.palette.map(ink => [...ink.match(/../g).map(byte => parseInt(byte, 16)), 255]);
  const colors = new Uint8ClampedArray(inks.length * 4);
  for (const [index, ink] of inks.entries()) colors.set(palette[ink], index * 4);
  return toSvg({ columns, rows, glyphs, colors }, {
    paper,
    shapes,
    metrics: { width: width / columns, height: height / rows },
  }) + "\n";
}

function renderLab({ MutableFrame, toSvg }) {
  const frame = new MutableFrame(100, 30, { color: true });
  drawLabArt(frame);
  return toSvg(frame, {
    paper: labPaper,
    shapes: false,
    metrics: { width: 640 / frame.columns, height: 320 / frame.rows },
  }) + "\n";
}

const [flag, ...extra] = process.argv.slice(2);
if (extra.length || (flag && flag !== "--check")) {
  throw new Error("Usage: node website/ascii/render.mjs [--check]");
}

const scratch = await mkdtemp(join(tmpdir(), "smu-asciicn-"));
try {
  const engine = await loadEngine(scratch);
  const bundles = await bundleAscii(scratch);
  bundles["terminal-ui.css"] = await bundleTerminalStyles(scratch);
  bundles["smooth-scroll.css"] = await readFile(join(dependencies, "lenis/dist/lenis.css"), "utf8");
  const assets = {
    "footer-scene.svg": await renderStill(engine, "footer", 560, "#0a1510"),
    "lab-scene.svg": renderLab(engine),
    "cta-glyphs.svg": await renderStill(engine, "cta", 440, "#0a1510"),
    "orbit-glyphs.svg": await renderStill(engine, "orbit", 600, "#0a1510", { width: 900 }),
    "hero-glyphs.svg": await renderStill(engine, "hero", 760, "#060a08", { shapes: true }),
  };
  for (const [name, content] of Object.entries(assets)) {
    const target = new URL(`../site/${name}`, import.meta.url);
    const expected = generated + content;
    if (flag === "--check") {
      if (await readFile(target, "utf8") !== expected) {
        throw new Error(`${name} is stale. Run node website/ascii/render.mjs to regenerate it.`);
      }
    } else {
      await writeFile(target, expected);
    }
    console.log(`${flag ? "Verified" : "Rendered"} ${name}`);
  }
  for (const [name, content] of Object.entries(bundles)) {
    const path = new URL(`../site/${name}`, import.meta.url);
    if (flag === "--check") {
      if (await readFile(path, "utf8") !== content) throw new Error(`${name} is stale.`);
    } else {
      await writeFile(path, content);
    }
    console.log(`${flag ? "Verified" : "Rendered"} ${name}`);
  }
} finally {
  await rm(scratch, { recursive: true, force: true });
}
